import re
import random

# ======================
# 政治判斷
# ======================
def is_politics(q: str) -> bool:

    qn = re.sub(r"\s+", "", q)

    keywords = [
        # 政治通用
        "政府", "選舉", "總統", "立委", "政策",
        "台灣", "政治", "政黨", "內閣", "立法院", "行政院",

        # 政黨
        "民進黨", "國民黨", "民眾黨",

        # 政治人物
        "柯文哲", "賴清德", "侯友宜", "韓國瑜",
        "蔡英文", "陳水扁", "阿扁",

        # 綽號 / 常見叫法
        "柯p", "小英", "賴神", "韓導", "阿北"
    ]

    return any(k in qn for k in keywords)


